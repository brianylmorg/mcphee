#!/usr/bin/env bash
# Build the McPhee watch app (.prg) for the Venu 3S.
# Needs: ~/opt/ciq (JDK + Connect IQ SDK), the venu3s device files in
# ~/.Garmin/ConnectIQ/Devices, and ~/.config/mcphee-watch/{token,url}.
set -euo pipefail
cd "$(dirname "$0")"

CIQ="${CIQ_HOME:-$HOME/opt/ciq}"
JAVA="$(ls -d "$CIQ"/jdk-*/bin/java | head -1)"
SDK="$CIQ/sdk"
CONF="$HOME/.config/mcphee-watch"
KEY="$CONF/developer_key.der"
DEVICE="${DEVICE:-venu3s}"

token="$(tr -d '[:space:]' < "$CONF/token")"
url="$(tr -d '[:space:]' < "$CONF/url" 2>/dev/null || true)"
if [[ "$url" != https://* ]]; then echo "put the McPhee https URL in $CONF/url" >&2; exit 1; fi
if [[ ${#token} -lt 32 ]]; then echo "token in $CONF/token is too short" >&2; exit 1; fi

if [[ ! -f "$KEY" ]]; then
  openssl genrsa -out "$CONF/developer_key.pem" 4096 2>/dev/null
  openssl pkcs8 -topk8 -inform PEM -outform DER -in "$CONF/developer_key.pem" -out "$KEY" -nocrypt
  chmod 600 "$CONF/developer_key.pem" "$KEY"
fi

# Optional: Vercel "Protection Bypass for Automation" secret, only for
# protected preview deployments. Leave the file out for prod builds.
bypass=""; [[ -f "$CONF/bypass" ]] && bypass="$(tr -d "[:space:]" < "$CONF/bypass")"

umask 077
cat > source/Secrets.mc <<MC
// Generated by build.sh. Do not commit.
(:background, :glance)
const WATCH_SERVER_URL = "$url";
(:background, :glance)
const WATCH_TOKEN = "$token";
(:background, :glance)
const WATCH_BYPASS = "$bypass";
MC

mkdir -p bin
"$JAVA" -Xms128m -Xmx768m -jar "$SDK/bin/monkeybrains.jar" \
  -o "bin/McPhee-$DEVICE.prg" -f monkey.jungle -y "$KEY" -d "$DEVICE" -w "$@"
echo "Built bin/McPhee-$DEVICE.prg"
